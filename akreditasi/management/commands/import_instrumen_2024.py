"""Management command: import_instrumen_2024

Imports the Kemenkes STARKES 2024 accreditation instrument into the database:
16 Categories (BAB), their Standards, and every Elemen Penilaian (EP) as a
``StandardItem`` with its RDWOS ``EvidenceReq`` rows.

Two sources are supported, and the fixture is the default because it is
versioned, reviewable, and does not require the 415-page PDF at deploy time:

* ``--fixture fixtures/standar_akreditasi_2024.json`` (default) — the golden
  fixture generated by ``akreditasi.instrumen_2024`` from the PDF;
* ``--pdf-path <file>`` — parse the PDF directly, for regenerating or
  cross-checking the fixture.

Usage::

    python manage.py import_instrumen_2024 --dry-run
    python manage.py import_instrumen_2024
    python manage.py import_instrumen_2024 --category TKRS --dry-run

The import is idempotent: standards and EPs are upserted by code, and evidence
requirements by ``(standard_item, category_type)``, so re-running it converges
instead of duplicating rows.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from akreditasi.models import Category, EvidenceReq, Framework, StandardItem, QualityRecord
from akreditasi import instrumen_2024, reconcile_2024

DEFAULT_FIXTURE = 'fixtures/standar_akreditasi_2024.json'
DEFAULT_PDF = Path.home() / 'Downloads' / 'instrumen standar survey akreditasi  rs 2024.pdf'

BAB_META = instrumen_2024.BAB_META
BAB_ORDER = instrumen_2024.BAB_ORDER
EVIDENCE_TYPES = instrumen_2024.EVIDENCE_TYPES


def load_fixture(path):
    """Load the golden fixture into ``{standard_code: [ep, ...]}``.

    The fixture records are validated on the way in: a record whose
    ``ep_count`` disagrees with its ``eps`` list, or whose ``bab_code`` is not
    one of the 16 chapters, aborts the import instead of writing bad data.
    """
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if not isinstance(data, list):
        raise CommandError(f'Fixture must be a JSON list: {path}')

    standards = {}
    for rec in data:
        code = rec.get('standard_code', '').strip()
        prefix = rec.get('bab_code', '').strip().upper()
        if not code or ' ' not in code:
            raise CommandError(f'Fixture record has no usable standard_code: {rec!r}')
        if prefix not in BAB_META:
            raise CommandError(f'Fixture record has unknown bab_code {prefix!r} ({code})')
        eps = rec.get('eps') or []
        if rec.get('ep_count') != len(eps):
            raise CommandError(
                f'Fixture record {code}: ep_count={rec.get("ep_count")} '
                f'but {len(eps)} eps')
        if not eps:
            raise CommandError(f'Fixture record {code} has no EP')
        standards[code] = [{
            'letter': str(ep.get('letter', '')).strip(),
            'description': re.sub(r'\s+', ' ', ep.get('description', '')).strip(),
            'evidence_types': sorted({t for t in ep.get('evidence_types', [])
                                      if t in EVIDENCE_TYPES}),
            'evidence_detail': re.sub(r'\s+', ' ', ep.get('evidence_detail', '')).strip(),
            'score': str(ep.get('score', '')).strip(),
        } for ep in eps]
    if not standards:
        raise CommandError(f'Fixture contains no standards: {path}')
    return standards


class Command(BaseCommand):
    help = 'Import STARKES 2024 accreditation standards & EP (fixture or PDF)'

    def add_arguments(self, parser):
        parser.add_argument(
            '--fixture',
            type=str,
            default=None,
            help=f'Path to the golden fixture JSON (default: {DEFAULT_FIXTURE})',
        )
        parser.add_argument(
            '--pdf-path',
            type=str,
            default=None,
            help='Parse this PDF instead of reading the fixture',
        )
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='Report what would change without writing to the database',
        )
        parser.add_argument(
            '--category',
            type=str,
            default=None,
            help='Limit the import to one chapter code (e.g. TKRS)',
        )
        parser.add_argument(
            '--framework-name',
            type=str,
            default='STARKES Edisi 2024 / Kemenkes RI',
            help='Framework the imported standards belong to',
        )
        parser.add_argument(
            '--prune',
            action='store_true',
            help='Delete EPs of an imported chapter that are absent from the source',
        )

    def handle(self, *args, **options):
        dry_run = options['dry_run']
        only_category = options['category'].upper() if options['category'] else None
        framework_name = options['framework_name']
        prune = options['prune']

        standards, provenance = self._load(options)

        if only_category:
            standards = {c: v for c, v in standards.items()
                         if c.split()[0] == only_category}
            if not standards:
                raise CommandError(f'No standards for category {only_category}')
            self.stdout.write(f'Filtered to {only_category}: {len(standards)} standards')

        audit = instrumen_2024.validate(standards)
        self._report_source(provenance, audit)

        if dry_run:
            self._dry_run_report(standards, audit, framework_name, prune)
            return

        self._import(standards, framework_name, prune)

    # -- source ------------------------------------------------------------
    def _load(self, options):
        pdf_path = options['pdf_path']
        fixture = options['fixture']

        if pdf_path:
            path = Path(pdf_path)
            if not path.exists():
                raise CommandError(f'PDF not found: {path}')
            self.stdout.write(f'Parsing PDF: {path}')
            standards = instrumen_2024.extract_pdf(path)
            return standards, {'kind': 'pdf', 'path': str(path),
                               'sha256': instrumen_2024.file_sha256(path)}

        path = Path(fixture) if fixture else Path(settings.BASE_DIR) / DEFAULT_FIXTURE
        if not path.is_absolute():
            path = Path(settings.BASE_DIR) / path
        if not path.exists():
            raise CommandError(f'Fixture not found: {path} (pass --pdf-path to parse a PDF)')
        self.stdout.write(f'Reading fixture: {path}')
        standards = load_fixture(path)

        sha = ''
        raw = json.loads(path.read_text(encoding='utf-8'))
        for rec in raw:
            if rec.get('source_pdf_sha256'):
                sha = rec['source_pdf_sha256']
                break
        return standards, {'kind': 'fixture', 'path': str(path), 'sha256': sha}

    # -- reporting ---------------------------------------------------------
    def _report_source(self, provenance, audit):
        self.stdout.write('')
        self.stdout.write(f"Source   : {provenance['kind']} — {provenance['path']}")
        if provenance['sha256']:
            self.stdout.write(f"PDF sha  : {provenance['sha256']}")
        self.stdout.write(f"Standards: {audit['standards']}   EP: {audit['eps']}")

        problems = []
        if audit['empty_description']:
            problems.append(f"empty description x{len(audit['empty_description'])}")
        if audit['duplicate_letters']:
            problems.append(f"duplicate letters x{len(audit['duplicate_letters'])}")
        if audit['contaminated_description']:
            problems.append(f"score contamination x{len(audit['contaminated_description'])}")
        if audit['header_leak']:
            problems.append(f"column-header leak x{len(audit['header_leak'])}")
        if problems:
            raise CommandError('Source failed validation: ' + '; '.join(problems))
        if audit['no_evidence_types']:
            self.stdout.write(self.style.WARNING(
                f"  {len(audit['no_evidence_types'])} EP carry no RDWOS marker"))

    def _dry_run_report(self, standards, audit, framework_name, prune):
        self.stdout.write('')
        self.stdout.write('=' * 68)
        self.stdout.write('DRY RUN — nothing written')
        self.stdout.write('=' * 68)

        for prefix in BAB_ORDER:
            row = audit['per_bab'][prefix]
            if not row['standards']:
                continue
            name = BAB_META[prefix]['name']
            self.stdout.write(
                f"  {prefix:8s} {name:45s} {row['standards']:3d} std  {row['eps']:4d} EP")
        self.stdout.write('-' * 68)
        self.stdout.write(
            f"  {'TOTAL':8s} {'':45s} {audit['standards']:3d} std  {audit['eps']:4d} EP")

        framework = Framework.objects.filter(name=framework_name).first()
        existing = set(StandardItem.objects.values_list('code', flat=True))

        if framework is None:
            # Dry-run pada database yang belum punya framework 2024 tetap harus
            # memperlihatkan rencana rekonsiliasi. Instance sementara ini tidak
            # disimpan; ia hanya dipakai untuk menghitung laporan.
            self.stdout.write(f"\n  Framework '{framework_name}': would be created")
            framework = Framework(name=framework_name, version='2024',
                                  cycle_type='PDCA')
            transient = True
        else:
            self.stdout.write(f"\n  Framework '{framework_name}': exists (id={framework.pk})")
            transient = False

        # Dry-run harus melaporkan rencana yang sama dengan yang nanti
        # dijalankan, bukan selisih mentah kode. Tanpa ini, dry-run pada
        # database berisi data 2022 menampilkan "create 800 / delete 299",
        # padahal import sebenarnya memetakan ulang 247 baris di tempat.
        report = reconcile_2024.reconcile(
            framework, standards,
            Category=Category, StandardItem=StandardItem,
            QualityRecord=QualityRecord, dry_run=True)
        self.stdout.write(f"  StandardItem now      : {len(existing)}")
        self.stdout.write(f"  Legacy EP remapped    : {report['retarget']}")
        self.stdout.write(f"  Legacy EP dropped     : {report['delete']}")
        self.stdout.write(f"  EP created from source: {report['create']}")
        if report['blocked']:
            self.stdout.write(self.style.ERROR(
                '  BLOCKED — EP berisi penilaian tanpa padanan 2024: '
                + ', '.join(report['blocked'][:10])))
        projected = len(existing) - report['delete'] + report['create']
        self.stdout.write(f"  Projected total       : {projected}")
        if transient:
            self.stdout.write('  (framework 2024 belum ada; angka di atas '
                              'dihitung terhadap data legacy yang ada)')

    # -- import ------------------------------------------------------------
    def _import(self, standards, framework_name, prune):
        framework, created = Framework.objects.get_or_create(
            name=framework_name,
            defaults={'version': '2024', 'cycle_type': 'PDCA'},
        )
        if created:
            self.stdout.write(self.style.SUCCESS(f'[NEW] Framework {framework_name}'))

        # Pindahkan dulu EP legacy ke kategori 2024. Tanpa langkah ini, kategori
        # 2022 dan 2024 hidup berdampingan dengan kode yang sama, ``Category``
        # lookup jadi ambigu, dan ``StandardItem.code`` yang unique membuat
        # upsert berikutnya gagal.
        report = reconcile_2024.reconcile(
            framework, standards,
            Category=Category, StandardItem=StandardItem,
            QualityRecord=QualityRecord)
        if report['blocked']:
            raise CommandError(
                'Rekonsiliasi dibatalkan: EP legacy berikut sudah berisi '
                'penilaian tetapi tidak punya padanan di instrumen 2024 — '
                + ', '.join(report['blocked'][:10])
                + (' ...' if len(report['blocked']) > 10 else ''))
        if report['retarget'] or report['delete']:
            self.stdout.write(
                f"  Rekonsiliasi legacy: {report['retarget']} EP dipetakan, "
                f"{report['delete']} EP kosong dibuang, "
                f"{report['categories_removed']} kategori lama dibersihkan")

        by_bab = defaultdict(list)
        for code in sorted(standards, key=instrumen_2024.sort_code_key):
            by_bab[code.split()[0]].append(code)

        stats = {'cat': 0, 'std_new': 0, 'std_upd': 0, 'ev': 0, 'pruned': 0}

        # One transaction per chapter: a remote-DB timeout on one chapter must
        # not roll back the chapters that already succeeded.
        for prefix in BAB_ORDER:
            codes = by_bab.get(prefix)
            if not codes:
                continue
            with transaction.atomic():
                meta = BAB_META[prefix]
                cat, _ = Category.objects.update_or_create(
                    framework=framework,
                    code=prefix,
                    defaults={'name': meta['name'], 'order': meta['order'],
                              'kelompok': meta['kelompok']},
                )
                stats['cat'] += 1

                seen_codes = set()
                order = 0
                for code in codes:
                    for ep in standards[code]:
                        order += 1
                        ep_code = f"{code} EP {ep['letter']}"
                        seen_codes.add(ep_code)
                        item, was_new = StandardItem.objects.update_or_create(
                            code=ep_code,
                            defaults={
                                'category': cat,
                                'sub_standard': code,
                                'sub_title': ep['evidence_detail'][:250],
                                'description': ep['description'][:2000],
                                'order': order,
                            },
                        )
                        if was_new:
                            stats['std_new'] += 1
                        else:
                            stats['std_upd'] += 1

                        for ev_type in ep['evidence_types']:
                            _, ev_new = EvidenceReq.objects.get_or_create(
                                standard_item=item,
                                category_type=ev_type,
                                defaults={
                                    'title': (ep['evidence_detail'] or
                                              f"Bukti {ev_type} — {ep_code}")[:300],
                                    'is_mandatory': True,
                                },
                            )
                            if ev_new:
                                stats['ev'] += 1

                # Target EP per bab dipakai dashboard sebagai penyebut
                # persentase cakupan. Disetel dari fixture, bukan dari hitungan
                # baris database, supaya "100%" berarti lengkap terhadap PDF.
                cat.target_ep_count = order
                cat.save(update_fields=['target_ep_count'])

                if prune:
                    stale = StandardItem.objects.filter(
                        category=cat).exclude(code__in=seen_codes)
                    stats['pruned'] += stale.count()
                    stale.delete()

            self.stdout.write(
                f"  {prefix:8s} {len(codes):3d} std  "
                f"{sum(len(standards[c]) for c in codes):4d} EP")

        self.stdout.write('')
        self.stdout.write('=' * 68)
        self.stdout.write(
            'IMPORT COMPLETE\n'
            f"  Categories      : {stats['cat']}\n"
            f"  StandardItem new: {stats['std_new']}\n"
            f"  StandardItem upd: {stats['std_upd']}\n"
            f"  EvidenceReq new : {stats['ev']}\n"
            f"  Pruned          : {stats['pruned']}"
        )
